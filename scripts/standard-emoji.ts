// node scripts/standard-emoji.ts — regenerates, from emoji-datasource (iamcal/emoji-data,
// MIT), the dataset Slack's own short names come from:
// - apps/server/src/api/standard-emoji.ts: the standard short names by Slack's categories,
//   which custom emoji may not take;
// - packages/core/src/emoji-chars.ts: every short name with its character, for apps to draw.
// Bump VERSION to follow new Unicode releases.

import { writeFileSync } from "node:fs"
import { resolve } from "node:path"

const VERSION = "15.1.2"
const SOURCE = `https://cdn.jsdelivr.net/npm/emoji-datasource@${VERSION}/emoji.json`

/** Slack's category names, in its picker's order, and the Unicode categories each takes. */
const CATEGORIES: [string, string[]][] = [
  ["smileys_people", ["Smileys & Emotion", "People & Body"]],
  ["nature", ["Animals & Nature"]],
  ["food_drink", ["Food & Drink"]],
  ["activity", ["Activities"]],
  ["travel_places", ["Travel & Places"]],
  ["objects", ["Objects"]],
  ["symbols", ["Symbols"]],
  ["flags", ["Flags"]],
]

interface Entry {
  unified: string
  short_name: string
  short_names: string[]
  category: string
  sort_order: number
}

const res = await fetch(SOURCE)
if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`)
const entries = ((await res.json()) as Entry[]).toSorted((a, b) => a.sort_order - b.sort_order)

const categories = CATEGORIES.map(([name, sources]) => {
  const names = sources.flatMap((s) => entries.filter((e) => e.category === s).map((e) => e.short_name))
  return [name, names.join(" ")]
})
const primary = new Set(entries.map((e) => e.short_name))
const shown = new Set(CATEGORIES.flatMap(([, s]) => s))
// Other names of the same emoji (thumbsup beside +1), and those in no category (the skin tones).
const other = [
  ...entries.filter((e) => !shown.has(e.category)).map((e) => e.short_name),
  ...entries.flatMap((e) => e.short_names.filter((n) => !primary.has(n))),
]

const out = `// Generated by scripts/standard-emoji.ts from emoji-datasource ${VERSION} (iamcal/emoji-data,
// MIT), the dataset Slack's short names come from. Don't edit by hand.

export const STANDARD_EMOJI_VERSION = "${VERSION}"

/** Slack's emoji categories, each with its emoji's short names (space-separated) in picker order. */
export const STANDARD_EMOJI_CATEGORIES: [string, string][] = ${JSON.stringify(categories)}

/** The other standard short names: second names of the same emoji (thumbsup), and the skin tones. */
export const STANDARD_EMOJI_OTHER = ${JSON.stringify(other.join(" "))}
`
const target = resolve(import.meta.dirname, "../apps/server/src/api/standard-emoji.ts")
writeFileSync(target, out)
console.log(`${target}: ${new Set([...primary, ...other]).size} names`)

// Name, space, character, space…: neither ever holds a space. About 37 KB, 15 KB gzipped.
const chars = entries.flatMap((e) => {
  const char = String.fromCodePoint(...e.unified.split("-").map((h) => Number.parseInt(h, 16)))
  return e.short_names.map((n) => `${n} ${char}`)
})
const charsOut = `// Generated by scripts/standard-emoji.ts from emoji-datasource ${VERSION} (iamcal/emoji-data,
// MIT), the dataset Slack's short names come from. Don't edit by hand.

/** Every standard short name and its character, as "name char name char …". */
export const EMOJI_CHARS = ${JSON.stringify(chars.join(" "))}
`
const charsTarget = resolve(import.meta.dirname, "../packages/core/src/emoji-chars.ts")
writeFileSync(charsTarget, charsOut)
console.log(`${charsTarget}: ${chars.length} names`)
