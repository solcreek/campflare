import { existsSync, readFileSync } from "node:fs"
import { resolve } from "node:path"
import tailwindcss from "@tailwindcss/vite"
import react from "@vitejs/plugin-react"
import type { Plugin } from "vite"
import { defineConfig } from "vitest/config"

const root = resolve(import.meta.dirname, "../..")
const source = (path: string) => resolve(root, path)

export interface DevAccounts {
  url: string
  /** User tokens by handle: "alex" (the owner), then everyone `pnpm dev:all` seeded. */
  people: Record<string, string>
}

/**
 * The `pnpm dev:all` server and its seeded people, so the dev app signs in by
 * itself (`?as=vincent` picks someone else). Only `vite serve` reads it: a
 * build never carries tokens.
 */
export function devAccounts(file = process.env.CAMPFLARE_DEV_ENV ?? source("apps/server/.wrangler/campflare-dev.env")) {
  if (!existsSync(file)) return null
  const env = Object.fromEntries(
    readFileSync(file, "utf8")
      .split("\n")
      .flatMap((line) => {
        const m = /^([A-Z_]+)=(.*)$/.exec(line)
        return m ? [[m[1]!, m[2]!]] : []
      }),
  )
  if (!env.CAMPFLARE_URL || !env.CAMPFLARE_TOKEN) return null
  const people: Record<string, string> = { alex: env.CAMPFLARE_TOKEN }
  for (const [key, value] of Object.entries(env)) {
    const m = /^CAMPFLARE_TOKEN_(.+)$/.exec(key)
    if (m) people[m[1]!.toLowerCase()] = value
  }
  return { url: env.CAMPFLARE_URL, people } satisfies DevAccounts
}

/**
 * The app's Client ID Metadata Document: how a server it signs in to knows it
 * (client_id is this document's own URL; see src/sign-in.ts). A public client,
 * coming back to the app's root.
 */
export function oauthClientDocument(origin: string) {
  const root = new URL(origin).origin
  return {
    client_id: `${root}/oauth-client.json`,
    client_name: "Campflare",
    client_uri: `${root}/`,
    redirect_uris: [`${root}/`],
    grant_types: ["authorization_code"],
    response_types: ["code"],
    token_endpoint_auth_method: "none",
  }
}

/** Emits oauth-client.json for a build that will be served at CAMPFLARE_WEB_ORIGIN (none without it). */
export function oauthClientPlugin(origin = process.env.CAMPFLARE_WEB_ORIGIN): Plugin {
  return {
    name: "campflare-oauth-client",
    apply: "build",
    generateBundle() {
      if (!origin) return
      this.emitFile({
        type: "asset",
        fileName: "oauth-client.json",
        source: `${JSON.stringify(oauthClientDocument(origin), null, 2)}\n`,
      })
    },
  }
}

